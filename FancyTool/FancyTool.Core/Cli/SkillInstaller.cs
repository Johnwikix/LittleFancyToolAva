namespace FancyToolAva.Cli;

/// <summary>一家 agent 的技能落点。各家均遵循 Agent Skills 开放标准（技能目录 + SKILL.md）。</summary>
/// <param name="Name">CLI 参数与结果输出使用的短名（如 claude、cursor）。</param>
/// <param name="Title">展示名（中英一致，产品名不翻译）。</param>
/// <param name="SkillDirectory">技能目录（相对用户主目录，受 FANCYTOOL_SKILL_HOME 重定向）。</param>
public sealed record SkillAgentTarget(string Name, string Title, string SkillDirectory);

public sealed record SkillInstallResult(string Target, string Path, bool Changed, string Message);

/// <summary>
/// 将 CLI 用法写入本机各主流 agent 的技能目录（同一份 SKILL.md 多处落盘），
/// 可选附加 Qoder 用户级 AGENTS.md 受管块。
/// 只维护带标记的受管内容，不覆盖用户已有段落；写入使用临时文件原子替换。
/// </summary>
public static class SkillInstaller
{
    public const string ManagedStart = "<!-- BEGIN FANCY-TOOL CLI (managed by FancyTool) -->";
    public const string ManagedEnd = "<!-- END FANCY-TOOL CLI (managed by FancyTool) -->";
    private const string SkillMarker = "<!-- generated by FancyTool; run `fancy-tool skill install --force` to refresh -->";

    /// <summary>
    /// 支持的 agent 注册表。目录约定（2026-11 各家官方文档一致）：
    /// Claude Code ~/.claude/skills、Cursor ~/.cursor/skills、Gemini CLI ~/.gemini/skills、
    /// Codex ~/.codex/skills、Copilot CLI ~/.copilot/skills、Qoder ~/.qoder-cn/skills。
    /// 全部走同一 SKILL.md 标准，因此一份内容直接多处落盘；AGENTS.md 类常驻指令文件
    /// （CLAUDE.md / GEMINI.md / instructions.md 等）不扩展——那是全量常驻上下文，
    /// 写入命令清单会污染每个会话，SKILL.md 的 frontmatter 按需触发才是正确机制。
    /// </summary>
    public static readonly IReadOnlyList<SkillAgentTarget> Agents =
    [
        new("claude", "Claude Code", Path.Combine(".claude", "skills", "fancy-tool")),
        new("cursor", "Cursor", Path.Combine(".cursor", "skills", "fancy-tool")),
        new("gemini", "Gemini CLI", Path.Combine(".gemini", "skills", "fancy-tool")),
        new("codex", "Codex", Path.Combine(".codex", "skills", "fancy-tool")),
        new("copilot", "GitHub Copilot CLI", Path.Combine(".copilot", "skills", "fancy-tool")),
        new("qoder", "Qoder", Path.Combine(".qoder-cn", "skills", "fancy-tool")),
    ];

    public static string UserHome =>
        Environment.GetEnvironmentVariable("FANCYTOOL_SKILL_HOME") is { Length: > 0 } overridden
            ? overridden
            : Environment.GetFolderPath(Environment.SpecialFolder.UserProfile);

    public static string AgentsFilePath => Path.Combine(UserHome, ".qoder-cn", "AGENTS.md");

    /// <summary>按短名解析 agent（忽略大小写）；找不到返回 null，由调用方决定错误呈现（CLI 层转用法错误）。</summary>
    public static SkillAgentTarget? ResolveAgent(string name) =>
        Agents.FirstOrDefault(a => string.Equals(a.Name, name, StringComparison.OrdinalIgnoreCase));

    /// <summary>安装到指定 agent（null = 全部），可选附加 Qoder AGENTS.md 受管块。</summary>
    public static async Task<IReadOnlyList<SkillInstallResult>> InstallAsync(
        IReadOnlyList<SkillAgentTarget>? agents, bool includeQoderAgentsMd, bool zh, bool force, CancellationToken ct = default)
    {
        var results = new List<SkillInstallResult>();
        foreach (SkillAgentTarget agent in agents ?? Agents)
            results.Add(await InstallSkillAsync(agent, zh, force, ct).ConfigureAwait(false));
        if (includeQoderAgentsMd)
            results.Add(await InstallAgentsFileAsync(zh, ct).ConfigureAwait(false));
        return results;
    }

    public static async Task<IReadOnlyList<SkillInstallResult>> UninstallAsync(
        IReadOnlyList<SkillAgentTarget>? agents, bool includeQoderAgentsMd, bool zh, CancellationToken ct = default)
    {
        var results = new List<SkillInstallResult>();
        foreach (SkillAgentTarget agent in agents ?? Agents)
            results.Add(UninstallSkill(agent, zh));
        if (includeQoderAgentsMd)
            results.Add(await UninstallAgentsFileAsync(zh, ct).ConfigureAwait(false));
        return results;
    }

    private static async Task<SkillInstallResult> InstallSkillAsync(SkillAgentTarget agent, bool zh, bool force, CancellationToken ct)
    {
        string path = Path.Combine(UserHome, agent.SkillDirectory, "SKILL.md");
        // SKILL.md 的 YAML frontmatter 必须从第一行开始；受管标记放在 frontmatter 之后。
        string document = CommandCatalog.RenderSkillMarkdown(zh).Replace("\r\n", "\n", StringComparison.Ordinal);
        int frontMatterEnd = document.IndexOf("\n---\n", 4, StringComparison.Ordinal);
        string content = frontMatterEnd >= 0
            ? document[..(frontMatterEnd + 5)] + SkillMarker + "\n" + document[(frontMatterEnd + 5)..]
            : SkillMarker + "\n" + document;
        content = ToCrlf(content);
        if (File.Exists(path))
        {
            string existing = await File.ReadAllTextAsync(path, ct).ConfigureAwait(false);
            if (string.Equals(ToCrlf(existing), content, StringComparison.Ordinal))
                return new(agent.Name, path, false, zh ? "技能已是最新版本。" : "Skill is already up to date.");
            if (!force && !existing.Contains(SkillMarker, StringComparison.Ordinal))
                return new(agent.Name, path, false, zh
                    ? "目标位置已存在非受管 SKILL.md；使用 --force 覆盖。"
                    : "A non-managed SKILL.md already exists; use --force to overwrite.");
        }
        Directory.CreateDirectory(Path.GetDirectoryName(path)!);
        await WriteAtomicAsync(path, content, ct).ConfigureAwait(false);
        return new(agent.Name, path, true, Msg(zh, $"已写入 {agent.Title} 技能。", $"{agent.Title} skill written."));
    }

    private static async Task<SkillInstallResult> InstallAgentsFileAsync(bool zh, CancellationToken ct)
    {
        string path = AgentsFilePath;
        string block = ManagedStart + "\r\n" + ToCrlf(CommandCatalog.RenderAgentsBlock(zh)) + ManagedEnd;
        string existing = File.Exists(path)
            ? await File.ReadAllTextAsync(path, ct).ConfigureAwait(false)
            : string.Empty;
        string updated = ReplaceManagedBlock(existing, block);
        updated = ToCrlf(updated);
        if (string.Equals(ToCrlf(existing), updated, StringComparison.Ordinal))
            return new("agents", path, false, zh ? "AGENTS.md 已是最新片段。" : "AGENTS.md already contains the current block.");
        Directory.CreateDirectory(Path.GetDirectoryName(path)!);
        await WriteAtomicAsync(path, updated, ct).ConfigureAwait(false);
        return new("agents", path, true, zh ? "已更新 AGENTS.md 受管片段。" : "AGENTS.md managed block updated.");
    }

    private static SkillInstallResult UninstallSkill(SkillAgentTarget agent, bool zh)
    {
        string path = Path.Combine(UserHome, agent.SkillDirectory, "SKILL.md");
        if (!File.Exists(path))
            return new(agent.Name, path, false, Msg(zh, "尚未安装。", "Not installed."));
        string content = File.ReadAllText(path);
        if (!content.Contains(SkillMarker, StringComparison.Ordinal))
            return new(agent.Name, path, false, Msg(zh, "SKILL.md 不是 FancyTool 生成的，保持原样。", "SKILL.md is not managed by FancyTool; left untouched."));
        File.Delete(path);
        try
        {
            string? directory = Path.GetDirectoryName(path);
            if (directory is not null && Directory.Exists(directory) && !Directory.EnumerateFileSystemEntries(directory).Any())
                Directory.Delete(directory);
        }
        catch
        {
            // best-effort cleanup
        }
        return new(agent.Name, path, true, Msg(zh, "已移除。", "Removed."));
    }

    private static async Task<SkillInstallResult> UninstallAgentsFileAsync(bool zh, CancellationToken ct)
    {
        string path = AgentsFilePath;
        if (!File.Exists(path)) return new("agents", path, false, Msg(zh, "尚未安装。", "Not installed."));
        string existing = await File.ReadAllTextAsync(path, ct).ConfigureAwait(false);
        string updated = RemoveManagedBlock(existing);
        if (string.Equals(existing, updated, StringComparison.Ordinal))
            return new("agents", path, false, Msg(zh, "没有 FancyTool 受管片段。", "No managed block found."));
        if (string.IsNullOrWhiteSpace(updated))
        {
            File.Delete(path);
            return new("agents", path, true, Msg(zh, "已移除受管片段，AGENTS.md 原本只有该片段，文件一并删除。", "Removed the managed block and the now-empty AGENTS.md."));
        }
        await WriteAtomicAsync(path, ToCrlf(updated), ct).ConfigureAwait(false);
        return new("agents", path, true, Msg(zh, "已移除受管片段，用户内容保持原样。", "Managed block removed; the rest of the file is untouched."));
    }

    private static string Msg(bool zh, string chinese, string english) => zh ? chinese : english;

    private static string ReplaceManagedBlock(string existing, string block)
    {
        int start = existing.IndexOf(ManagedStart, StringComparison.Ordinal);
        int end = start < 0 ? -1 : existing.IndexOf(ManagedEnd, start, StringComparison.Ordinal);
        if (start >= 0 && end >= 0)
        {
            end += ManagedEnd.Length;
            return existing[..start] + block + existing[end..];
        }
        if (string.IsNullOrWhiteSpace(existing)) return block + "\r\n";
        return existing.TrimEnd() + "\r\n\r\n" + block + "\r\n";
    }

    private static string RemoveManagedBlock(string existing)
    {
        int start = existing.IndexOf(ManagedStart, StringComparison.Ordinal);
        int end = start < 0 ? -1 : existing.IndexOf(ManagedEnd, start, StringComparison.Ordinal);
        if (start < 0 || end < 0) return existing;
        end += ManagedEnd.Length;
        string prefix = existing[..start].TrimEnd();
        string suffix = existing[end..].TrimStart();
        if (prefix.Length == 0) return suffix;
        if (suffix.Length == 0) return prefix + "\r\n";
        return prefix + "\r\n\r\n" + suffix;
    }

    private static async Task WriteAtomicAsync(string path, string content, CancellationToken ct)
    {
        string temporary = path + ".tmp-" + Guid.NewGuid().ToString("N");
        try
        {
            await File.WriteAllTextAsync(temporary, content, new System.Text.UTF8Encoding(encoderShouldEmitUTF8Identifier: false), ct)
                .ConfigureAwait(false);
            File.Move(temporary, path, overwrite: true);
        }
        finally
        {
            try { if (File.Exists(temporary)) File.Delete(temporary); } catch { }
        }
    }

    private static string ToCrlf(string text) =>
        text.Replace("\r\n", "\n", StringComparison.Ordinal).Replace("\n", "\r\n", StringComparison.Ordinal);
}
